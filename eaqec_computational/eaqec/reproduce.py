def reproduce(output_directory: str | Path, *, deep: bool = True) -> dict[str, object]:
    output = Path(output_directory)
    tables = output / "tables"
    verified_tables = tables / "aeaqec_mds"
    paper_tables = tables / "paper_stated"
    manifest: dict[str, object] = {
        "schema_version": 1,
        "eaqec_examples": [],
        "aeaqec_verified_examples": [],
        "paper_stated_examples": [],
    }

    for p in EAQEC_EXAMPLE_PRIMES:
        path = tables / f"eaqec_p{p}.csv"
        count = write_eaqec_csv(eaqec_family(p), path)
        expected = (p - 1) * (p - 2) // 2
        if count != expected:
            raise ArithmeticError(f"family size mismatch for p={p}: {count} != {expected}")
        manifest["eaqec_examples"].append(
            {"p": p, "rows": count, "file": str(path.relative_to(output))}
        )

    for p in AEAQEC_EXAMPLE_PRIMES:
        verified_path = verified_tables / f"aeaqec_mds_p{p}.csv"
        verified_count = write_aeaqec_csv(aeaqec_family(p, orientation="both"), verified_path)
        expected = (p - 1) * (p - 2)
        if verified_count != expected:
            raise ArithmeticError(
                f"two-orientation family size mismatch for p={p}: {verified_count} != {expected}"
            )
        manifest["aeaqec_verified_examples"].append(
            {
                "p": p,
                "rows": verified_count,
                "orientations": ["natural", "swapped"],
                "file": str(verified_path.relative_to(output)),
            }
        )

        paper_path = paper_tables / f"paper_3_20_p{p}.csv"
        paper_count = write_paper_aeaqec_csv(paper_3_20_family(p), paper_path)
        manifest["paper_stated_examples"].append(
            {
                "p": p,
                "rows": paper_count,
                "status": "paper-stated-unverified",
                "file": str(paper_path.relative_to(output)),
            }
        )

    verification = run_verification(deep=deep)
    verification["reported_table_comparisons"] = {
        "table_22": compare_table_22(),
        "table_34": compare_table_34(),
        "table_23_manual_reading_note": {
            "anomalous_row": "[[11,4,15;14]]_11",
            "reason": "d=15>n=11 and c=14>n=11; absent from the generated formula family",
        },
    }
    if not verification["pass"]:
        raise ArithmeticError("independent verification failed; see verification.json")
    _write_json(output / "verification.json", verification)
    (output / "VERIFICATION_REPORT.md").write_text(
        _verification_markdown(verification), encoding="utf-8"
    )
    manifest["verification"] = {
        "pass": verification["pass"],
        "deep": deep,
        "s1_pair_cases": verification["scope"]["s1_pair_cases"],
        "report": "VERIFICATION_REPORT.md",
        "data": "verification.json",
    }
    _write_json(output / "summary.json", manifest)
    return manifest
